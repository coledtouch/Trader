"""Fernet helpers for secrets at rest (the owner's TOTP secret).

The key comes from TRADER_SECRET_KEY (written to .env by `python -m trader setup`).
Errors never include key material.
"""

from __future__ import annotations

from cryptography.fernet import Fernet, InvalidToken
from pydantic import SecretStr


class SecretKeyError(RuntimeError):
    """TRADER_SECRET_KEY is missing, malformed, or not the key the data was encrypted with."""


def generate_secret_key() -> str:
    """A new random Fernet key (urlsafe base64, 32 bytes) for TRADER_SECRET_KEY."""
    return Fernet.generate_key().decode("ascii")


def _fernet(key: str | SecretStr) -> Fernet:
    raw = key.get_secret_value() if isinstance(key, SecretStr) else key
    raw = (raw or "").strip()
    if not raw:
        raise SecretKeyError(
            "TRADER_SECRET_KEY is not set. Run `python -m trader setup` to generate it."
        )
    try:
        return Fernet(raw.encode("ascii"))
    except (ValueError, TypeError, UnicodeEncodeError):
        raise SecretKeyError(
            "TRADER_SECRET_KEY is invalid: expected a urlsafe-base64 32-byte Fernet key "
            "as generated by `python -m trader setup`."
        ) from None


def validate_secret_key(key: str | SecretStr) -> None:
    """Raise SecretKeyError unless `key` is a usable Fernet key."""
    _fernet(key)


def encrypt(key: str | SecretStr, plaintext: str) -> str:
    return _fernet(key).encrypt(plaintext.encode("utf-8")).decode("ascii")


def decrypt(key: str | SecretStr, token: str) -> str:
    fernet = _fernet(key)
    try:
        return fernet.decrypt(token.encode("ascii")).decode("utf-8")
    except (InvalidToken, UnicodeError):
        raise SecretKeyError(
            "cannot decrypt the stored secret: TRADER_SECRET_KEY does not match the key used "
            "at setup (restore the original key or run `python -m trader reset-2fa`)."
        ) from None
